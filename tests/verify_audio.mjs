// verify_audio.mjs — SF25 gate: every soft planet-action sound EXISTS as a
// wav, is PRELOADED by AudioSystem, and is REFERENCED by at least one sfx()
// call in PlanetScene — with all NEW sfx volumes <= 0.45 (never louder than
// the existing harvest cue). Fails loudly if a wav drifts away or a call is
// unwired/over-loud.
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

let pass = 0, fail = 0;
function check(name, cond, detail = '') {
  if (cond) pass++;
  else { fail++; console.log(`  ✗ ${name} ${detail}`); }
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => readFileSync(path.join(root, rel), 'utf8');

const NEW_KEYS = ['till', 'plant', 'mine_hit', 'ore', 'fish_catch', 'sell', 'equip', 'door', 'refill', 'tired'];

const audioJs = read('client/systems/AudioSystem.js');
const sceneJs = read('client/scenes/PlanetScene.js');
const genPy = read('gen_sounds.py');

// sfx() calls in PlanetScene: capture key + optional explicit volume
const callRe = /\.sfx\(\s*'([\w-]+)'(?:\s*,\s*\{\s*volume\s*:\s*([\d.]+))?/g;
const calls = [];
let m;
while ((m = callRe.exec(sceneJs)) !== null) {
  calls.push({ key: m[1], volume: m[2] === undefined ? null : parseFloat(m[2]) });
}

for (const key of NEW_KEYS) {
  // 1. the wav file exists (generated by gen_sounds.py)
  check(`wav exists: sounds/${key}.wav`, existsSync(path.join(root, 'sounds', `${key}.wav`)));
  // 2. gen_sounds.py actually declares it (so regeneration keeps it)
  check(`gen_sounds declares '${key}.wav'`, genPy.includes(`'${key}.wav':`));
  // 3. preloaded by AudioSystem.preload()
  check(`preloaded '${key}'`, audioJs.includes(`scene.load.audio('${key}', '/sounds/${key}.wav')`));
  // 4. referenced by at least one sfx() call in PlanetScene
  const used = calls.filter(c => c.key === key);
  check(`referenced '${key}' by >=1 sfx() call`, used.length >= 1, `(found ${used.length})`);
  // 5. every NEW sfx volume <= 0.45 (explicit or <= 0.45 default)
  for (const c of used) {
    check(`volume <=0.45 for '${key}'`, c.volume === null || c.volume <= 0.45, `(volume ${c.volume})`);
  }
  if (used.length === 0) {
    check(`explicit volume <=0.45 for '${key}' (no call found)`, false);
  }
}

console.log(`\naudio wired: ${pass} passed, ${fail} failed`);
process.exit(fail === 0 ? 0 : 1);
